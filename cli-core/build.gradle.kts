/**
 * The version, compiled in rather than typed twice.
 *
 * `--version` used to be a string literal in `Main.kt`, which meant a tagged release shipped four
 * numbers that could disagree: the binary's, the `.deb`'s `Version:`, the container tag and the
 * GitHub release. Installing `loopky_0.2.0_amd64.deb` and being told `loopky 0.1.0` is the first
 * thing a new user sees, because `install.sh` ends by running `--version`.
 *
 * One number, in `gradle.properties`, and the release workflow refuses a tag that disagrees with
 * it. Generated Kotlin rather than a resource so it is compile-time and needs no reachability
 * registration in the native image. Here rather than in `:cli` because the image prober sends it
 * as its User-Agent, and the prober is a command.
 */
val cliVersion: String = providers.gradleProperty("loopkyCliVersion").get()

val generateCliVersion = tasks.register("generateCliVersion") {
    val version = cliVersion
    val outputDir = layout.buildDirectory.dir("generated/version")
    outputs.dir(outputDir)
    inputs.property("version", version)
    doLast {
        val file = outputDir.get().asFile.resolve("com/github/jvsena42/loopky/cli/BuildVersion.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            // Generated by :cli-core:generateCliVersion from `loopkyCliVersion` in gradle.properties.
            package com.github.jvsena42.loopky.cli

            const val CLI_VERSION = "$version"

            """.trimIndent(),
        )
    }
}

/**
 * The CLI's command layer: the deck, card, import and tag commands, and the result, error
 * and view types they answer in.
 *
 * A library so that `:cli` and the hosted MCP server are two front ends over one set of
 * command functions rather than two implementations. The rule for what lives here: anything a
 * hosted server would call. Anything about being a terminal binary on someone's machine — `Main`,
 * sign-in by QR, install and update, completions, the native-image metadata — stays in `:cli`.
 *
 * The packages are `com.github.jvsena42.loopky.cli…`, the same as before the split, and that is
 * load-bearing: `:cli`'s reachability metadata lists classes by name, and a renamed one drops out
 * of it silently. No Koin and no `presentation/` — callers hand the commands their repositories.
 */
kotlin {
    jvmToolchain(17)
    sourceSets.main { kotlin.srcDir(generateCliVersion) }
}

dependencies {
    api(projects.shared)
    api(libs.kotlinx.coroutines.core)
    api(libs.kotlinx.serialization.json)
    testImplementation(libs.kotlin.test)
    testImplementation(libs.kotlinx.coroutines.test)
}

// `:shared` exports Koin, so without this the "no Koin" rule above would be a comment: an
// `org.koin` import here would compile, and tie the library to a started graph a server may not
// have. Compile only — `:shared` still needs Koin at runtime, and consumers bring their own.
configurations.named("compileClasspath") {
    exclude(group = "io.insert-koin")
}

tasks.withType<Test>().configureEach {
    useJUnitPlatform()
}
